class Brain:
    """
    Brain class that connects to the LLM model.
    """
    def __init__(self, config: SimpleNamespace):
        self.logger = getLogger(self.__class__.__name__)
        self.config = config
        self.logger.info("🚀 Connecting to LLM Model '%s' ...", config.brain.model)
        llm_only = lms.list_downloaded_models("llm")
        for model in llm_only:
            if config.brain.model == model.model_key:
                break
        else:
            raise ValueError(f"The configured Model '{config.brain.model}' is not available.")
        try:
            current_model = lms.llm()
            current_model_info = current_model.get_info()
            if current_model_info.model_key != config.brain.model:
                self.logger.info("Unloading Model [%s]", current_model_info.model_key)
                current_model.unload()
        except lms.LMStudioClientError:
            pass

        self.model = lms.llm(config.brain.model)
        self.info = self.model.get_info()
        self.context_window = int(float(self.config.brain.context_ratio)*self.info.context_length)
        self.system_path = pathlib.Path(self.config.brain.system_path) if self.config.brain.system_path else None
        if self.system_path and self.system_path.exists() and self.system_path.is_file():
            self.chat = lms.Chat(initial_prompt=self.system_path.read_text(encoding="utf-8"))
        else:
            raise ValueError(f"System prompt file '{self.system_path}' does not exist or is not a file.")

        self._chat_cfg = {
            "temperature": self.config.brain.temperature,
            "maxTokens": self.context_window,
        }
        self.logger.info("✅ LLM Model '%s' connected.", self.config.brain.model)

    def model_fragments(self, prompt: str) -> PredictionStream:
        """
        Get response fragments as stream from the model for a given prompt.
        Toos are not supported in this method, so the response is purely generated by the model.
        """
        self.logger.info("Sending to Model [🤖: %s] ...", self.config.brain.model)
        self.logger.debug("Prompt:\n%s", prompt)
        self.chat.add_user_message(prompt)
        resp_stream = self.model.respond_stream(
            self.chat,
            on_message=self.chat.append,
            config=self._chat_cfg,
        )
        return resp_stream

    @staticmethod
    def print_fragment(fragment):
        """Print a response fragment to the console. This can be used as a callback for streaming responses."""
        print(fragment.content, end="", flush=True)

    def model_response(self, prompt: str) -> str:
        """
        Get the full response from the model for a given prompt.
        Tools are not supported in this method, so the response is purely generated by the model.
        """
        resp_stream = self.model_fragments(prompt)
        answer:list[str] = [fragment.content for fragment in resp_stream]
        response = " ".join(answer).strip()
        self.logger.debug("Response:\n%s", response)
        return response


class ChatHistory:
    """
    Class to manage the history of interactions with the model.
    It can save and load history from a text file.
    """
    def __init__(self, history_path: pathlib.Path, buffer_size: int = 5):
        self.history_path = history_path
        self._buffer:list[str] = []
        self._buffer_size = buffer_size
        if not self.history_path.exists():
            self.history_path.touch()

    def _build_message(self, role: str, content: str) -> str:
        now = datetime.now(tz=timezone.utc)
        timestamp = now.strftime("%A, %B %d, %Y at %I:%M %p, %Z")
        return f"[{timestamp}] role: {role}, content: {content}"

    def append(self, message: str):
        """Append a message to the history and save it to the file."""
        self._buffer.append(message)
        if len(self._buffer) > self._buffer_size:
            with open(self.history_path, "a", encoding="utf-8") as f:
                f.write("\n".join(self._buffer) + "\n")
            self._buffer.clear()

    def append_message(self, role: str, content: str):
        """Build a message with timestamp and append it to the history."""
        message = self._build_message(role, content)
        self.append(message)    


class Agent(Brain):
    """
    Agent class that extends the Brain with tool usage capabilities and message history.
    """
    def __init__(self, config: SimpleNamespace):
        super().__init__(config)
        self._history = ChatHistory(history_path=self.config.brain.history_path)
        self._fragments_buffer:list[str] = []
        self.logger.info("✅ Agent with Model '%s' initialized. Setting up tools ...", self.config.brain.model)
        self.tools:list[Callable] = [
            self.image_response, self.allow_speech, self.recall_history,
            exit_gracefully, system_info, current_date_time,  read_text_file, write_text_file, get_working_directory, run_command,
            webpage_headlines, capture_image, save_financial_chart
        ]
        self.logger.info("✅ Agent with Model '%s' is ready with [%d] tools.", self.config.brain.model, len(self.tools))

    def _handle_fragment(self, fragment, round_index=0):
        self._fragments_buffer.append(fragment.content)
        print(fragment.content, end="", flush=True)

    def _handle_round_end(self, round_index=0):
        formatted = self.model.apply_prompt_template(self.chat)
        token_count = len(self.model.tokenize(formatted))
        context_usage_percentage = float(token_count/self.context_window) * 100
        print(f"[context: {context_usage_percentage:.2f} %]")
        response = " ".join(self._fragments_buffer).strip()
        if hasattr(self, "speech"):
            self.speech.speak(response)
        self._fragments_buffer.clear()
        self._history.append_message("assistant", response)

    def allow_speech(self, enable:bool):
        """
        Enable or disable speech for Agent responses.
        When enabled, the Agent will use the Speech Generator to vocalize its responses after each round of interaction.
        It can be toggled on the fly during the conversation.
        """
        print(f"calling: allow_speech [{enable}]")
        if enable and not hasattr(self, "speech"):
            self.logger.info("Enabling speech for Agent responses. Initializing Speech Generator ...")
            self.speech = SpeechGenerator(
                model_path=self.config.speech_gen.model_path,
                samplerate=self.config.speech_gen.samplerate
            )
            self.logger.info("✅ Speech Generator initialized.")
        elif not enable and hasattr(self, "speech"):
            self.logger.info("Disabling speech for Agent responses. Releasing Speech Generator ...")
            del self.speech
            self.logger.info("✅ Speech Generator released.")

    def image_response(self, prompt:str = "describe the image", image:str = CAPTURED_IMAGE) -> str:
        """
        Provide text response form an input image.
        Useful when user asks for getting a description of the input image content. 
        """
        print(f"calling: image_response [{prompt}, {image}]")
        if not self.info.vision:
            return "Cannot handle images"
        image_handle = lms.prepare_image(image)
        self.chat.add_user_message(prompt, images=[image_handle])
        self._history.append_message("user", prompt)
        prediction  = self.model.respond(self.chat)
        return prediction.content
    
    def recall_history(self) -> str:
        """
        Recall the last n rounds of conversation history.
        Useful when user asks to recall what has been discussed in the past.
        """
        print("calling: recall_history")
        if self.config.brain.history_path and self.config.brain.history_path.exists():
            return self.config.brain.history_path.read_text(encoding="utf-8")
        return "No history available."

    def act(self, prompt: str):
        """
        Perform an action based on the input prompt. 
        The response may involve using tools or just generating a text.
        """
        self.logger.info("Sending to Agent [🤖: %s] ...", self.config.brain.model)
        self.logger.debug("Prompt:\n%s", prompt)
        self.chat.add_user_message(prompt)
        self._history.append_message("user", prompt)
        self.model.act(
            self.chat,
            self.tools,
            on_message=self.chat.append,
            config=self._chat_cfg,
            on_prediction_fragment=self._handle_fragment,
            on_round_end=self._handle_round_end
        )


class LiveAi:
    """
    Interactive AI agent that listens to user input via speech and tools.
    """
    def __init__(self, config: SimpleNamespace):
        self.logger = getLogger(self.__class__.__name__)
        self.config = config
        self.detector = SpeechDetector(
            model_path=config.speech_det.model_path, 
            language=config.speech_det.language
        )
        self.agent = Agent(config=config)

    def run(self):
        print(f"\n🤖 [{self.config.brain.model}]: ", end="", flush=True)
        self.agent.act(self.config.brain.bootstrap_prompt)
        print("\nReady. Press Ctrl+C to quit.")
        while True:
            try:
                prompt = self.detector.listen_and_transcribe(
                    silence_timeout_s=self.config.speech_det.silence_timeout_s,
                )
                if not prompt:
                    self.logger.info("Empty transcription, skipping.")
                    continue
                print(f"\nYou: {prompt}")
                print(f"\n🤖 [{self.config.brain.model}]: ", end="", flush=True)
                self.agent.act(prompt)
                print("\n---\n")
            except KeyboardInterrupt:
                print("\n👋 Exiting.")
                break
